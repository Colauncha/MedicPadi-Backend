// Rewrites <app>/src/database/migrations/index.ts so it lists every migration in the folder.
// The app bundles migrations through this index, so a migration missing from it never runs.
// Usage: node scripts/sync-migration-index.mjs apps/<service>
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const appDir = process.argv[2];
if (!appDir) {
  console.error('Usage: node scripts/sync-migration-index.mjs apps/<service>');
  process.exit(1);
}

const dir = join(appDir, 'src/database/migrations');
const files = readdirSync(dir)
  .filter((f) => /^\d+-.+\.ts$/.test(f))
  .sort((a, b) => Number(a.split('-')[0]) - Number(b.split('-')[0]));

const entries = files.map((file) => {
  const source = readFileSync(join(dir, file), 'utf8');
  const match = source.match(/export class (\w+)/);
  if (!match) throw new Error(`No exported migration class in ${file}`);
  return { className: match[1], module: `./${file.replace(/\.ts$/, '')}` };
});

const content = `// Generated by scripts/sync-migration-index.mjs; do not edit by hand.
// Imported explicitly (not globbed) so webpack bundles the migrations into the app.
${entries.map((e) => `import { ${e.className} } from '${e.module}';`).join('\n')}

export const migrations = [${entries.length ? `\n${entries.map((e) => `  ${e.className},`).join('\n')}\n` : ''}];
`;

writeFileSync(join(dir, 'index.ts'), content);
console.log(`${join(dir, 'index.ts')}: ${entries.length} migration(s)`);
